fun formatCurrency(amount: Double, symbol: String = "$"): String {
    val dfs = DecimalFormatSymbols(Locale.US).apply {
        groupingSeparator = ','
        decimalSeparator = '.'
    }
    val df = DecimalFormat("#,##0.00", dfs)
    return "$symbol ${df.format(amount)}"
}

fun formatQuantity(quantity: Double, unit: String = "pza"): String {
    return if (quantity % 1.0 == 0.0) {
        "${quantity.toInt()} $unit"
    } else {
        String.format(Locale.US, "%.2f %s", quantity, unit)
    }
}

@Composable
fun MetricCard(
    title: String,
    value: String,
    subtitle: String? = null,
    icon: ImageVector,
    iconBgColor: Color = MaterialTheme.colorScheme.primaryContainer,
    iconTint: Color = MaterialTheme.colorScheme.primary,
    modifier: Modifier = Modifier,
    onClick: (() -> Unit)? = null
